// Translate only known backend wording; keep opaque error details and paths intact.
function shellStatusText(source) {
  const text = String(source ?? "");
  const patterns = [
    [/^Доступна версия (.+)$/u, "Доступна версия {version}", ["version"]],
    [/^Проверка не выполнена: ([\s\S]*)$/u, "Проверка не выполнена: {error}", ["error"]],
    [/^OBS не ответил: (.+)$/u, "OBS не ответил: {request}", ["request"]],
    [/^Обновите OBS: отсутствует (.+)$/u, "Обновите OBS: отсутствует {request}", ["request"]],
    [/^Twitch отклонил запрос: HTTP (\d+)$/u, "Twitch отклонил запрос: HTTP {status}", ["status"]],
    [/^Twitch отозвал доступ: (.+)$/u, "Twitch отозвал доступ: {reason}", ["reason"]],
    [/^Помощник установки завершился \(([^)]+)\)\. Подробности в helper\.log: ([\s\S]+)$/u, "Помощник установки завершился ({code}). Подробности в helper.log: {path}", ["code", "path"]],
    [/^Помощник установки сообщил об ошибке\. См\. result\.json: ([\s\S]+)$/u, "Помощник установки сообщил об ошибке. См. result.json: {path}", ["path"]],
  ];
  for (const [pattern, template, keys] of patterns) {
    const match = text.match(pattern);
    if (match) return tr(template, Object.fromEntries(keys.map((key, i) => [
      key, key === "error" ? tr(match[i + 1]) : match[i + 1],
    ])));
  }
  return tr(text);
}

